#include<iostream>
using namespace std;
int main(){
  int x = 4;
  cout<<x<<endl;
  --x;
  cout<<x<<endl;
//Pre increment
  int y = 6;
  cout<<y<<endl;
  cout<<++y<<endl;
  cout<<y<<endl;

//Post increment
  int z = 9;
  cout<<z<<endl;
  cout<<z++<<endl;
  cout<<z<<endl;
  
//Pre decrement
 int r = 11;
 cout<<r<<endl;
 cout<<--r<<endl;
 cout<<r<<endl;
 
//Post decrement
int s = 15;
cout<<s<<endl;
cout<<s--<<endl;
cout<<s<<endl;


}